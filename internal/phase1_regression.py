#!/usr/bin/env python3
"""Single authoritative Phase-1 acceptance regression entry point."""

import argparse
import os
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path


INTERNAL = Path(__file__).resolve().parent
TOOLS = INTERNAL.parent
ROOT = TOOLS.parent
CSIM = ROOT / "csim"
RTL = ROOT / "rtl"
RTL_TB = RTL / "tb"


def require(path):
    if not Path(path).exists():
        raise RuntimeError(f"required Phase-1 asset is missing: {path}")


def run(name, command, cwd, reject_skip=False):
    print(f"\n=== {name} ===", flush=True)
    proc = subprocess.Popen(
        command, cwd=cwd, text=True,
        stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
    )
    saw_skip = False
    assert proc.stdout is not None
    for line in proc.stdout:
        print(line, end="")
        normalized = line.strip().upper()
        if normalized.startswith("SKIP") or " SKIP:" in normalized:
            saw_skip = True
    rc = proc.wait()
    if rc:
        raise RuntimeError(f"{name} failed with exit code {rc}")
    if reject_skip and saw_skip:
        raise RuntimeError(f"{name} reported SKIP; Phase-1 gates may not skip")


def check_cocotb_xml(allow_filtered_skips=False):
    result = RTL_TB / "results.xml"
    require(result)
    root = ET.parse(result).getroot()
    failures = len(root.findall(".//failure")) + len(root.findall(".//error"))
    skipped = len(root.findall(".//skipped"))
    tests = len(root.findall(".//testcase"))
    passed = tests - failures - skipped
    invalid_skips = skipped and not allow_filtered_skips
    if tests == 0 or passed == 0 or failures or invalid_skips:
        raise RuntimeError(
            f"invalid cocotb result: tests={tests}, failures={failures}, skipped={skipped}"
        )


def run_rtl_test(name, dut, module=None, testcase=None):
    build = f"/tmp/open_npu_phase1_{name}"
    command = [
        "make", f"DUT={dut}", "SIM=icarus", f"SIM_BUILD={build}",
    ]
    if module:
        command.append(f"MODULE={module}")
    if testcase:
        command.append(f"TESTCASE={testcase}")
    run(f"RTL {name}", command, RTL_TB)
    check_cocotb_xml(allow_filtered_skips=testcase is not None)


def preflight():
    for tool in ("make", "gcc", "python3", "iverilog", "verilator", "yosys"):
        if shutil.which(tool) is None:
            raise RuntimeError(f"required tool is missing: {tool}")
    for path in (
        ROOT / "csim" / "Makefile",
        ROOT / "csim" / "npu_sim",
        ROOT / "rtl" / "Makefile",
        ROOT / "soc" / "run_model_e2e.sh",
        ROOT / "soc" / "firmware" / "build_main_ram.py",
        "/data/sam/onnx_quant/MODEL_A.onnx",
        "/data/sam/onnx_quant/a3_test_images",
        "/data/sam/model_b/WXPay_PalmIrLiveness_624_06_r20260509.onnx",
        "/data/sam/model_b/debug.bin",
    ):
        require(path)


def run_design(full):
    run("converter/capacity guards",
        ["python3", "tests/test_phase1_guards.py"], INTERNAL)
    run("model packer Python + CSIM E2E",
        ["python3", "model_packer.py", "test"], TOOLS)
    if not full:
        return

    # Never accept cached binaries generated by an older converter.
    for path in (
        "/tmp/int16_e2e_test",
        "/tmp/model_a_e2e_phase3",
        "/tmp/model_b_e2e",
    ):
        shutil.rmtree(path, ignore_errors=True)

    tests = (
        "bn_pool.py",
        "flatten_fc.py",
        "resize.py",
        "concat.py",
        "pipeline_e2e.py",
        "mobilenetv2.py",
        "resnet18_e2e.py",
        "model_a_e2e.py",
        "model_b_e2e.py",
        "yolo_tiny_e2e.py",
        "int16_e2e.py",
    )
    for test in tests:
        run(f"design {test}", ["python3", f"tests/{test}"], INTERNAL,
            reject_skip=True)


def run_csim():
    run("CSIM build and unit/E2E tests", ["make", "clean", "all", "test"], CSIM)


def run_rtl(full):
    if full:
        full128 = RTL_TB / "golden" / "golden_full_model_128" / "int8"
        for asset in (
            full128 / "metadata.json",
            full128 / "inv_000_wgt_words.npy",
            full128 / "inv_000_param_words.npy",
            full128 / "inv_000_input_words.npy",
            full128 / "inv_000_output_words.npy",
        ):
            require(asset)

    run("RTL lint", ["make", "lint"], RTL)
    if full:
        run("RTL synthesis", ["make", "syn"], RTL)

    run_rtl_test("controller", "npu_ctrl")
    run_rtl_test(
        "global_avgpool_8x8", "npu_top", "e2e.test_npu_dma_e2e",
        "test_pool_avg_global_8x8",
    )
    if not full:
        return

    for dut in (
        "npu_ppu", "npu_csr", "npu_sram",
        "npu_dma", "npu_dw_conv", "npu_compute",
    ):
        run_rtl_test(dut, dut)

    run_rtl_test("compute_integration", "npu_compute_tb",
                 "integration.test_npu_compute_tb")
    run_rtl_test("conv_trace", "npu_compute_tb", "integration.test_conv_trace")
    run_rtl_test("dw_trace", "npu_compute_tb", "integration.test_dw_trace")
    run_rtl_test("top_integration", "npu_top", "integration.test_npu_top")

    for module in (
        "test_random_stress", "test_csr_complete", "test_dma_robust",
        "test_edge_cases", "test_abort_reset", "test_wb_protocol",
    ):
        run_rtl_test(module, "npu_top", f"robustness.{module}")

    run_rtl_test("all_e2e", "npu_top", "e2e.test_npu_dma_e2e")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--quick", action="store_true",
        help="run smoke gates only; this does not qualify for tagging",
    )
    parser.add_argument(
        "--section",
        choices=("all", "design", "csim", "rtl", "matrix"),
        default="all",
    )
    args = parser.parse_args()
    full = not args.quick

    preflight()
    if args.section in ("all", "csim"):
        run_csim()
    if args.section in ("all", "design"):
        run_design(full)
    if args.section in ("all", "rtl"):
        run_rtl(full)
    if full and args.section in ("all", "matrix"):
        run("SoC output poison self-test",
            ["python3", "build_main_ram.py", "--self-test"],
            ROOT / "soc" / "firmware")
        run("Phase-1 10-cell matrix (cosine + SoC RTL)",
            ["python3", "phase1_model_matrix.py", "--rtl"],
            INTERNAL, reject_skip=True)
    elif args.section == "matrix":
        raise RuntimeError("--quick cannot run the 10-cell matrix")

    qualifier = "FULL" if full and args.section == "all" else "PARTIAL"
    print(f"\nPHASE-1 REGRESSION {qualifier}: PASS")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (RuntimeError, OSError) as exc:
        print(f"\nPHASE-1 REGRESSION: FAIL: {exc}", file=sys.stderr)
        sys.exit(1)
